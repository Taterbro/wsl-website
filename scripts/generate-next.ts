function formatProblem(problem: Problem): string {
  const where = [
    problem.owner,
    problem.section ? `section "${problem.section}"` : undefined,
    problem.field ? `field "${problem.field}"` : undefined,
  ]
    .filter(Boolean)
    .join(" / ");

  const fix = problem.suggestion ? `\n      fix: ${problem.suggestion}` : "";
  return `  - ${where}: ${problem.message}${fix}`;
}

function printProblems(title: string, problems: Problem[]) {
  if (problems.length === 0) return;
  console.log(`${title} (${problems.length})`);
  for (const problem of problems) console.log(formatProblem(problem));
  console.log("");
}

function registerType(name: string, owner: string) {
  const existing = typeNames.get(name);
  if (existing) {
    error({
      owner,
      message: `Generated type name "${name}" collides with ${existing}.`,
      suggestion:
        "Rename the page, section, field, or collection, or add a collection names override.",
    });
    return;
  }
  typeNames.set(name, owner);
}

function registerFunction(name: string, owner: string, kind: string) {
  const existing = functionNames.get(name);
  if (existing) {
    error({
      owner,
      message: `Generated function name "${name}" collides with ${existing}.`,
      suggestion:
        "Rename the page, section, field, or collection, or add a collection names override.",
    });
    return;
  }
  functionNames.set(name, `${kind} for ${owner}`);
  functionRows.push({ name, owner, kind });
}

function pascalCase(value: string): string {
  return value
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

function camelCase(value: string): string {
  const pascal = pascalCase(value);
  return pascal ? pascal[0].toLowerCase() + pascal.slice(1) : pascal;
}

function fileSlug(value: string): string {
  return value
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
}

