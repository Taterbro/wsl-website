function capitalizeLike(value: string, original: string): string {
  if (!value) return value;
  return original[0] === original[0].toUpperCase()
    ? value[0].toUpperCase() + value.slice(1)
    : value;
}

function pluralizePascal(word: string): string {
  const lower = word.toLowerCase();
  const irregular = IRREGULAR_PLURALS[lower];
  if (irregular) return capitalizeLike(irregular, word);
  if (UNCOUNTABLE.has(lower)) return word;
  if (/(s|x|z|ch|sh)$/.test(lower)) return `${word}es`;
  if (/[^aeiou]y$/.test(lower)) return `${word.slice(0, -1)}ies`;
  return `${word}s`;
}

function propertyKey(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function propertyAccess(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? `.${name}` : `[${JSON.stringify(name)}]`;
}

function uniqueSorted(values: string[]): string[] {
  return [...new Set(values)].sort();
}

function fingerprint(fields: Field[]): string {
  return JSON.stringify(
    fields.map((field) => ({
      name: field.name,
      type: field.type,
      collection: field.collection ?? null,
      fields: field.fields ? JSON.parse(fingerprint(field.fields)) : null,
    }))
  );
}

async function loadAll<T>(dir: string): Promise<Loaded<T>[]> {
  const files = fs
    .readdirSync(dir)
    .filter((file) => file.endsWith(".ts") && file !== "constants.ts")
    .sort();

  return Promise.all(
    files.map(async (file) => {
      const filePath = path.resolve(dir, file);
      const schema = (await import(pathToFileURL(filePath).href)).default as T;
      return { file, schema };
    })
  );
}

function validateFields(
  fields: unknown,
  owner: string,
  section: string | undefined,
  fieldPath: string,
  collectionSlugs: Set<string>
) {
  if (!Array.isArray(fields)) {
    error({
      owner,
      section,
      field: fieldPath || undefined,
      message: "Fields must be an array.",
      suggestion: "Provide a fields array on the schema.",
    });
    return;
  }

  const seen = new Map<string, number>();

  fields.forEach((raw, index) => {
    if (!raw || typeof raw !== "object") {
      error({
        owner,
        section,
        field: fieldPath ? `${fieldPath}[${index}]` : `[${index}]`,
        message: "Field must be an object.",
        suggestion: "Provide a field object with name, type, and type-specific options.",
      });
      return;
    }

    const field = raw as Field;
    const name = typeof field.name === "string" ? field.name : "";
    const currentPath = fieldPath
      ? `${fieldPath}${name ? `.${name}` : `[${index}]`}`
      : name || `[${index}]`;

    if (!name) {
      error({
        owner,
        section,
        field: currentPath,
        message: "Field is missing a name.",
        suggestion: "Add a unique snake_case name to the field.",
      });
      return;
    }

    if (seen.has(name)) {
      error({
        owner,
        section,
        field: currentPath,
        message: `Duplicate field name "${name}" in the same field list.`,
        suggestion: "Rename one of the duplicate fields.",
      });
      return;
    }
    seen.set(name, index);

    const type = typeof field.type === "string" ? field.type : "";
    const definition = FIELD_TYPES[type];

    if (!definition) {
      error({
        owner,
        section,
        field: currentPath,
        message: `Unknown field type "${type || "(missing)"}".`,
        suggestion: `Use one of: ${Object.keys(FIELD_TYPES).join(", ")}.`,
      });
      return;
    }

    if (type === "repeater") {
      if (!Array.isArray(field.fields) || field.fields.length === 0) {
        error({
          owner,
          section,
          field: currentPath,
          message: "Repeater field has no sub-fields.",
          suggestion: "Add at least one sub-field to the repeater.",
        });
        return;
      }
      validateFields(
        field.fields,
        owner,
        section,
        `${currentPath}[]`,
        collectionSlugs
      );
    }

    if (type === "relationship") {
      if (!field.collection || typeof field.collection !== "string") {
        error({
          owner,
          section,
          field: currentPath,
          message: "Relationship field is missing a collection target.",
          suggestion: "Add collection: \"<post-type-slug>\" to the field.",
        });
      } else if (!collectionSlugs.has(field.collection)) {
        error({
          owner,
          section,
          field: currentPath,
          message: `Relationship targets unknown collection "${field.collection}".`,
          suggestion: `Use one of: ${[...collectionSlugs].sort().join(", ")}.`,
        });
      }

      if (field.filter !== undefined) {
        warning({
          owner,
          section,
          field: currentPath,
          message: "Relationship filter is ignored by the generator.",
          suggestion:
            "Remove filter from the schema or filter in the consuming component; generated fetchers preserve editor order.",
        });
      }
    }
  });
}

function validatePage(
  loaded: Loaded<PageSchema>,
  collectionSlugs: Set<string>
) {
  const { schema } = loaded;
  const slug =
    schema?.page && typeof schema.page.slug === "string"
      ? schema.page.slug
      : "";
  const owner = slug ? `page "${slug}"` : `page schema "${loaded.file}"`;

  if (!slug) {
    error({
      owner,
      message: "Page schema is missing page.slug.",
      suggestion: "Add page: { slug, label } to the default export.",
    });
  }

  if (!schema?.page || typeof schema.page.label !== "string") {
    error({
      owner,
      message: "Page schema is missing page.label.",
      suggestion: "Add a human-readable label to page.",
    });
  }

  if (!schema?.sections || typeof schema.sections !== "object") {
    error({
      owner,
      message: "Page schema is missing sections.",
      suggestion: "Add a sections object keyed by section name.",
    });
    return;
  }

  for (const [name, section] of Object.entries(schema.sections)) {
    if (!section || typeof section !== "object") {
      error({
        owner,
        section: name,
        message: "Section must be an object.",
        suggestion: "Provide { label, fields } for the section.",
      });
      continue;
    }

    if (typeof section.label !== "string") {
      error({
        owner,
        section: name,
        message: "Section is missing a label.",
        suggestion: "Add a human-readable label to the section.",
      });
    }

    validateFields(section.fields, owner, name, "", collectionSlugs);
  }
}

function validateCollection(
  loaded: Loaded<CollectionSchema>,
  collectionSlugs: Set<string>
) {
  const { schema } = loaded;
  const slug =
    schema?.postType && typeof schema.postType.slug === "string"
      ? schema.postType.slug
      : "";
  const owner = slug
    ? `collection "${slug}"`
    : `collection schema "${loaded.file}"`;

  if (!slug) {
    error({
      owner,
      message: "Collection schema is missing postType.slug.",
      suggestion: "Add postType: { slug, label } to the default export.",
    });
  }

  if (!schema?.postType || typeof schema.postType.label !== "string") {
    error({
      owner,
      message: "Collection schema is missing postType.label.",
      suggestion: "Add a human-readable label to postType.",
    });
  }

  validateFields(schema?.fields, owner, undefined, "", collectionSlugs);

  if (Array.isArray(schema?.fields)) {
    for (const field of schema.fields) {
      if (["id", "slug", "postTitle"].includes(field.name)) {
        error({
          owner,
          field: field.name,
          message: `Collection field "${field.name}" collides with a generated base field.`,
          suggestion:
            "Rename the field; id, slug, and postTitle are reserved generated fields.",
        });
      }
    }
  }
}

function collectTypeDecls(rootName: string, fields: Field[]): TypeDecl[] {
  const declarations: TypeDecl[] = [];

  function visit(typeName: string, currentFields: Field[]) {
    declarations.push({ name: typeName, fields: currentFields });
    for (const field of currentFields) {
      if (field.type === "repeater" && field.fields) {
        visit(`${typeName}${pascalCase(field.name)}`, field.fields);
      }
    }
  }

  visit(rootName, fields);
  return declarations;
}

function buildCollectionInfo(
  loaded: Loaded<CollectionSchema>
): CollectionInfo | undefined {
  const schema = loaded.schema;
  if (!schema?.postType?.slug) return undefined;

  const slug = schema.postType.slug;
  const owner = `collection "${slug}"`;
  const singularType = pascalCase(
    schema.names?.singular ?? schema.name ?? slug
  );
  let pluralType = pascalCase(
    schema.names?.plural ?? schema.plural ?? pluralizePascal(singularType)
  );

  if (pluralType.toLowerCase() === singularType.toLowerCase()) {
    pluralType = `${singularType}List`;
    warning({
      owner,
      message: `Collection name "${singularType}" is uncountable; using "${pluralType}".`,
      suggestion: "Add names.plural to the collection schema to override it.",
    });
  }

  const typeDecls = collectTypeDecls(singularType, schema.fields);
  const deps = uniqueSorted(
    schema.fields.flatMap((field) => dependenciesOf(field))
  );

  for (const decl of typeDecls) registerType(decl.name, owner);

  const listFunction = `get${pluralType}`;
  const bySlugFunction = `get${singularType}`;
  const normalizerFunction = `to${singularType}`;

  registerFunction(listFunction, owner, "collection list fetcher");
  registerFunction(bySlugFunction, owner, "collection by-slug fetcher");
  registerFunction(normalizerFunction, owner, "collection normalizer");

  return {
    slug,
    label: schema.postType.label,
    file: loaded.file,
    fields: schema.fields,
    singularType,
    pluralType,
    depsKey: camelCase(pluralType),
    listFunction,
    bySlugFunction,
    normalizerFunction,
    typeDecls,
    deps,
  };
}

function pageSectionTypeName(pagePascal: string, sectionName: string): string {
  return `${pagePascal}${pascalCase(sectionName)}`;
}

function buildSharedSections(
  pages: Loaded<PageSchema>[]
): Map<string, SectionInfo> {
  const occurrences = new Map<
    string,
    { pageSlug: string; section: SectionSchema; fingerprint: string }[]
  >();

  for (const { schema } of pages) {
    if (!schema?.page?.slug || !schema.sections) continue;
    for (const [name, section] of Object.entries(schema.sections)) {
      if (!occurrences.has(name)) occurrences.set(name, []);
      occurrences.get(name)!.push({
        pageSlug: schema.page.slug,
        section,
        fingerprint: fingerprint(section.fields),
      });
    }
  }

  const shared = new Map<string, SectionInfo>();

  for (const [name, list] of occurrences) {
    if (list.length < 2) continue;

    const shapes = new Map<string, string[]>();
    for (const item of list) {
      if (!shapes.has(item.fingerprint)) shapes.set(item.fingerprint, []);
      shapes.get(item.fingerprint)!.push(item.pageSlug);
    }

    if (shapes.size > 1) {
      const pagesByShape = [...shapes.values()]
        .map((pageSlugs) => pageSlugs.join(", "))
        .join(" | ");
      warning({
        owner: `section "${name}"`,
        message: `Section name is reused with ${shapes.size} different field shapes across pages: ${pagesByShape}.`,
        suggestion:
          "Align the fields to share one fetcher, or use the generated page-scoped section fetchers.",
      });
      continue;
    }

    const first = list[0];
    const typeName = pascalCase(name);
    const owner = `shared section "${name}"`;
    const typeDecls = collectTypeDecls(typeName, first.section.fields);
    const deps = uniqueSorted(
      first.section.fields.flatMap((field) => dependenciesOf(field))
    );
    const normalizeName = `normalize${typeName}`;
    const fetchName = `get${typeName}`;

    for (const decl of typeDecls) registerType(decl.name, owner);
    registerFunction(normalizeName, owner, "section normalizer");
    registerFunction(fetchName, owner, "shared section fetcher");

    shared.set(name, {
      name,
      label: first.section.label,
      fields: first.section.fields,
      typeName,
      normalizeName,
      fetchName,
      shared: true,
      owner,
      typeDecls,
      deps,
      async: first.section.fields.some((field) => isAsyncField(field)),
    });
  }

  return shared;
}

function buildPageInfo(
  loaded: Loaded<PageSchema>,
  sharedSections: Map<string, SectionInfo>
): PageInfo | undefined {
  const schema = loaded.schema;
  if (!schema?.page?.slug || !schema.sections) return undefined;

  const slug = schema.page.slug;
  const pagePascal = pascalCase(slug);
  const owner = `page "${slug}"`;
  const typeName = `${pagePascal}Page`;
  const fetchName = `get${typeName}`;

  registerType(typeName, owner);
  registerFunction(fetchName, owner, "page fetcher");

  const sections: SectionInfo[] = [];

  for (const [name, section] of Object.entries(schema.sections)) {
    const shared = sharedSections.get(name);
    if (shared) {
      sections.push(shared);
      continue;
    }

    const sectionTypeName = pageSectionTypeName(pagePascal, name);
    const sectionOwner = `page "${slug}"`;
    const typeDecls = collectTypeDecls(sectionTypeName, section.fields);
    const deps = uniqueSorted(
      section.fields.flatMap((field) => dependenciesOf(field))
    );
    const normalizeName = `normalize${sectionTypeName}`;
    const fetchName = `get${sectionTypeName}`;

    for (const decl of typeDecls) registerType(decl.name, sectionOwner);
    registerFunction(normalizeName, sectionOwner, "section normalizer");
    registerFunction(fetchName, sectionOwner, "section fetcher");

    sections.push({
      name,
      label: section.label,
      fields: section.fields,
      typeName: sectionTypeName,
      normalizeName,
      fetchName,
      shared: false,
      owner: sectionOwner,
      typeDecls,
      deps,
      async: section.fields.some((field) => isAsyncField(field)),
    });
  }

  const deps = uniqueSorted(sections.flatMap((section) => section.deps));

  return {
    slug,
    label: schema.page.label,
    file: loaded.file,
    typeName,
    fetchName,
    sections,
    deps,
  };
}

function renderFieldTs(
  field: Field,
  parentType: string,
  collections: Map<string, CollectionInfo>
): string {
  if (field.type === "repeater") {
    return `${parentType}${pascalCase(field.name)}[]`;
  }

  const definition = FIELD_TYPES[field.type];
  return definition.ts(field, {
    typeName: parentType,
    rowType: (rowField, rowParent) =>
      `${rowParent}${pascalCase(rowField.name)}`,
    collectionType: (slug) => collections.get(slug)!.singularType,
  });
}

function renderTypeDecl(
  declaration: TypeDecl,
  collections: Map<string, CollectionInfo>
): string {
  const properties = declaration.fields.map(
    (field) =>
      `  ${propertyKey(field.name)}: ${renderFieldTs(
        field,
        declaration.name,
        collections
      )};`
  );

  return `export type ${declaration.name} = {\n${properties.join("\n")}\n};`;
}

function createNormalizerRenderer(
  deps: string[],
  collections: Map<string, CollectionInfo>
) {
  let rowCounter = 0;
  const nextRowName = () => `row${rowCounter++}`;

  function renderEntry(field: Field, source: string): string {
    const expression = renderField(
      field,
      `${source}${propertyAccess(field.name)}`
    );
    return `  ${propertyKey(field.name)}: ${expression},`;
  }

  function renderObject(fields: Field[], source: string): string {
    return `{\n${fields
      .map((field) => renderEntry(field, source))
      .join("\n")}\n}`;
  }

  function renderField(field: Field, source: string): string {
    const definition = FIELD_TYPES[field.type];
    return definition.normalize(field, {
      source,
      deps: "deps",
      nextRowName,
      normalizeObject: (fields, source) => renderObject(fields, source),
      isAsync: (fields) => hasRelationshipDeep(fields),
      collectionType: (slug) => collections.get(slug)!.singularType,
      collectionDepsKey: (slug) => collections.get(slug)!.depsKey,
    });
  }

  return { renderEntry, renderObject };
}

function renderDepsType(
  deps: string[],
  collections: Map<string, CollectionInfo>
): string {
  if (deps.length === 0) return "";
  const properties = deps.map((slug) => {
    const collection = collections.get(slug)!;
    return `${collection.depsKey}: ${collection.singularType}[]`;
  });
  return `{ ${properties.join("; ")} }`;
}

function renderDepsValue(
  deps: string[],
  collections: Map<string, CollectionInfo>
): string {
  return `{ ${deps
    .map((slug) => collections.get(slug)!.depsKey)
    .join(", ")} }`;
}

function renderDepsFetch(
  deps: string[],
  collections: Map<string, CollectionInfo>
): string {
  if (deps.length === 0) return "";

  const names = deps.map((slug) => collections.get(slug)!.depsKey);
  const calls = deps.map((slug) => collections.get(slug)!.listFunction);

  if (deps.length === 1) {
    return `  const ${names[0]} = await ${calls[0]}();`;
  }

  return `  const [${names.join(", ")}] = await Promise.all([
    ${calls.map((call) => `${call}()`).join(",\n    ")},
  ]);`;
}

function renderDepsTags(
  deps: string[],
  collections: Map<string, CollectionInfo>
): string {
  return deps
    .map((slug) => `  cacheTag("collection_${collections.get(slug)!.slug}");`)
    .join("\n");
}

function renderDepsImports(
  deps: string[],
  collections: Map<string, CollectionInfo>,
  from: "collections" | "pages" | "sections"
): string {
  return deps
    .map((slug) => {
      const collection = collections.get(slug)!;
      const target = fileSlug(slug);
      const importPath = from === "collections" ? `./${target}` : `../collections/${target}`;
      return `import { ${collection.listFunction}, type ${collection.singularType} } from "${importPath}";`;
    })
    .join("\n");
}

function renderCollectionType(
  collection: CollectionInfo,
  collections: Map<string, CollectionInfo>
): string {
  const hasTitle = collection.fields.some((field) => field.name === "title");
  const properties = [
    "  id: number;",
    "  slug: string;",
    "  postTitle: string;",
    ...(hasTitle ? [] : ["  title: string;"]),
    ...collection.fields.map(
      (field) =>
        `  ${propertyKey(field.name)}: ${renderFieldTs(
          field,
          collection.singularType,
          collections
        )};`
    ),
  ];

  return `export type ${collection.singularType} = {\n${properties.join(
    "\n"
  )}\n};`;
}

function renderCollectionNormalizer(
  collection: CollectionInfo,
  collections: Map<string, CollectionInfo>
): string {
  const deps = collection.deps;
  const depsParam =
    deps.length > 0 ? `, deps: ${renderDepsType(deps, collections)}` : "";
  const isAsync = collection.fields.some((field) => isAsyncField(field));
  const returnType = isAsync
    ? `Promise<${collection.singularType}>`
    : collection.singularType;
  const hasTitle = collection.fields.some((field) => field.name === "title");
  const renderer = createNormalizerRenderer(deps, collections);
  const fieldEntries = collection.fields.map(
    (field) => `    ${renderer.renderEntry(field, "data").trim()}`
  );

  const entries = [
    "    id: item.id,",
    "    slug: item.slug,",
    "    postTitle: toStr(item.title?.rendered),",
    ...(hasTitle ? [] : ["    title: toStr(data.title),"]),
    ...fieldEntries,
  ];

  return `${isAsync ? "async " : ""}function ${
    collection.normalizerFunction
  }(item: ${collection.singularType}Body${depsParam}): ${returnType} {
  const data = toRecord(item.acf);
  return {
${entries.join("\n")}
  };
}`;
}

function renderCollectionModule(
  collection: CollectionInfo,
  collections: Map<string, CollectionInfo>
): string {
  const deps = collection.deps;
  const isAsync = collection.fields.some((field) => isAsyncField(field));
  const depsValue = deps.length > 0 ? `, ${renderDepsValue(deps, collections)}` : "";
  const depsFetch = renderDepsFetch(deps, collections);
  const depsTags = renderDepsTags(deps, collections);
  const depsImports = renderDepsImports(deps, collections, "collections");
  const rowTypes = collection.typeDecls
    .slice(1)
    .map((decl) => renderTypeDecl(decl, collections))
    .join("\n\n");
  const normalizer = renderCollectionNormalizer(collection, collections);

  const listBody = isAsync
    ? `  return Promise.all(items.map((item) => ${collection.normalizerFunction}(item${depsValue})));`
    : `  return items.map((item) => ${collection.normalizerFunction}(item${depsValue}));`;

  return `${HEADER}
import "server-only";

import { cacheLife, cacheTag } from "next/cache";

import { cmsGet } from "../../client";
import {
  pickByIds,
  toArray,
  toIds,
  toImage,
  toStr,
  type CmsImage,
} from "../../normalize";
import { toRecord } from "../_shared";
${depsImports ? `\n${depsImports}` : ""}

${renderCollectionType(collection, collections)}

type ${collection.singularType}Body = {
  id: number;
  slug: string;
  title: { rendered?: string } | null;
  acf: Record<string, unknown> | null;
};

${rowTypes ? `${rowTypes}\n\n` : ""}${normalizer}

export async function ${collection.listFunction}(): Promise<${collection.singularType}[]> {
  "use cache";
  cacheLife("hours");
  cacheTag("collection_${collection.slug}");
${depsTags ? `${depsTags}\n` : ""}
  const items = await cmsGet<${collection.singularType}Body[]>("${collection.slug}", {
    per_page: 100,
    _fields: "id,slug,title,acf",
  });
${depsFetch ? `\n${depsFetch}\n` : "\n"}${listBody}
}

export async function ${collection.bySlugFunction}(slug: string): Promise<${collection.singularType} | null> {
  "use cache";
  cacheLife("hours");
  cacheTag("collection_${collection.slug}");
${depsTags ? `${depsTags}\n` : ""}
  const all = await ${collection.listFunction}();
  return all.find((item) => item.slug === slug) ?? null;
}
`;
}

function renderSectionTypes(
  section: SectionInfo,
  collections: Map<string, CollectionInfo>
): string {
  return section.typeDecls
    .map((decl) => renderTypeDecl(decl, collections))
    .join("\n\n");
}

function renderSectionNormalizer(
  section: SectionInfo,
  collections: Map<string, CollectionInfo>
): string {
  const depsParam =
    section.deps.length > 0
      ? `, deps: ${renderDepsType(section.deps, collections)}`
      : "";
  const returnType = section.async
    ? `Promise<${section.typeName}>`
    : section.typeName;
  const renderer = createNormalizerRenderer(section.deps, collections);
  const object = renderer.renderObject(section.fields, "data");

  return `export ${section.async ? "async " : ""}function ${section.normalizeName}(value: unknown${depsParam}): ${returnType} {
  const data = toRecord(value);
  return ${object};
}`;
}

function renderSectionFetchBody(
  section: SectionInfo,
  collections: Map<string, CollectionInfo>
): string {
  const depsFetch = renderDepsFetch(section.deps, collections);
  const depsValue =
    section.deps.length > 0
      ? `, ${renderDepsValue(section.deps, collections)}`
      : "";
  return `${depsFetch ? `\n${depsFetch}\n` : "\n"}  return ${section.normalizeName}(acf${propertyAccess(
    section.name
  )}${depsValue});`;
}

function renderPageSectionFetcher(
  section: SectionInfo,
  pageSlug: string,
  collections: Map<string, CollectionInfo>
): string {
  const depsTags = renderDepsTags(section.deps, collections);
  return `export async function ${section.fetchName}(): Promise<${section.typeName}> {
  "use cache";
  cacheLife("hours");
  cacheTag("page_${pageSlug}");
${depsTags ? `${depsTags}\n` : ""}
  const acf = await getPageAcf("${pageSlug}");
${renderSectionFetchBody(section, collections)}
}`;
}

function renderSharedSectionModule(
  section: SectionInfo,
  collections: Map<string, CollectionInfo>
): string {
  const depsTags = renderDepsTags(section.deps, collections);
  const depsImports = renderDepsImports(section.deps, collections, "sections");
  const depsFetch = renderDepsFetch(section.deps, collections);
  const depsValue =
    section.deps.length > 0
      ? `, ${renderDepsValue(section.deps, collections)}`
      : "";

  return `${HEADER}
import "server-only";

import { cacheLife, cacheTag } from "next/cache";

import { getPageAcf } from "../../page";
import {
  pickByIds,
  toArray,
  toIds,
  toImage,
  toStr,
  type CmsImage,
} from "../../normalize";
import { toRecord } from "../_shared";
${depsImports ? `\n${depsImports}` : ""}

${renderSectionTypes(section, collections)}

${renderSectionNormalizer(section, collections)}

export async function ${section.fetchName}(pageSlug: string): Promise<${section.typeName}> {
  "use cache";
  cacheLife("hours");
  cacheTag(\`page_\${pageSlug}\`);
${depsTags ? `${depsTags}\n` : ""}
  const acf = await getPageAcf(pageSlug);
${depsFetch ? `\n${depsFetch}\n` : "\n"}  return ${section.normalizeName}(acf${propertyAccess(
    section.name
  )}${depsValue});
}
`;
}

function renderPageModule(
  page: PageInfo,
  sharedSections: Map<string, SectionInfo>,
  collections: Map<string, CollectionInfo>
): string {
  const pageSectionFetchers = page.sections
    .filter((section) => !section.shared)
    .map((section) => renderPageSectionFetcher(section, page.slug, collections))
    .join("\n\n");

  const sharedImports = [...sharedSections.values()]
    .filter((section) =>
      page.sections.some((pageSection) => pageSection.name === section.name)
    )
    .map(
      (section) =>
        `import { ${section.normalizeName}, type ${section.typeName} } from "../sections/${fileSlug(
          section.name
        )}";`
    )
    .join("\n");

  const depsImports = renderDepsImports(page.deps, collections, "pages");
  const depsTags = renderDepsTags(page.deps, collections);
  const depsFetch = renderDepsFetch(page.deps, collections);

  const pageTypeProperties = page.sections.map(
    (section) =>
      `  ${propertyKey(section.name)}: ${section.typeName};`
  );

  const pageObjectEntries = page.sections.map((section) => {
    const depsValue =
      section.deps.length > 0
        ? `, ${renderDepsValue(section.deps, collections)}`
        : "";
    const call = `${section.normalizeName}(acf${propertyAccess(
      section.name
    )}${depsValue})`;
    return `    ${propertyKey(section.name)}: ${
      section.async ? `await ${call}` : call
    },`;
  });

  return `${HEADER}
import "server-only";

import { cacheLife, cacheTag } from "next/cache";

import { getPageAcf } from "../../page";
import {
  pickByIds,
  toArray,
  toIds,
  toImage,
  toStr,
  type CmsImage,
} from "../../normalize";
import { toRecord } from "../_shared";
${depsImports ? `\n${depsImports}` : ""}
${sharedImports ? `\n${sharedImports}` : ""}

${page.sections
  .filter((section) => !section.shared)
  .flatMap((section) =>
    section.typeDecls.map((decl) => renderTypeDecl(decl, collections))
  )
  .join("\n\n")}

export type ${page.typeName} = {
${pageTypeProperties.join("\n")}
};

${page.sections
  .filter((section) => !section.shared)
  .map((section) => renderSectionNormalizer(section, collections))
  .join("\n\n")}

${pageSectionFetchers ? `${pageSectionFetchers}\n\n` : ""}export async function ${page.fetchName}(): Promise<${page.typeName}> {
  "use cache";
  cacheLife("hours");
  cacheTag("page_${page.slug}");
${depsTags ? `${depsTags}\n` : ""}
  const acf = await getPageAcf("${page.slug}");
${depsFetch ? `\n${depsFetch}\n` : "\n"}  return {
${pageObjectEntries.join("\n")}
  };
}
`;
}

function renderSharedModule(): string {
  return `${HEADER}
export type CmsRecord = Record<string, unknown>;

export function toRecord(value: unknown): CmsRecord {
  return value !== null && typeof value === "object" && !Array.isArray(value)
    ? (value as CmsRecord)
    : {};
}
`;
}

function renderReport(
  collections: CollectionInfo[],
  pages: PageInfo[]
): string {
  const rows = functionRows
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((row) => `| \`${row.name}\` | ${row.owner} | ${row.kind} |`)
    .join("\n");

  const warningRows =
    warnings.length > 0
      ? warnings.map((problem) => formatProblem(problem)).join("\n")
      : "  - None";

  return `<!-- AUTO-GENERATED by scripts/generate-next.ts. DO NOT EDIT. -->
# Generated CMS API

## Functions

| Function | Owner | Kind |
| --- | --- | --- |
${rows}

## Warnings

${warningRows}

## Collections

${collections
  .map(
    (collection) =>
      `- \`${collection.singularType}\` / \`${collection.pluralType}\` from \`${collection.slug}\``
  )
  .join("\n")}

## Pages

${pages.map((page) => `- \`${page.typeName}\` from \`${page.slug}\``).join("\n")}
`;
}

async function writeGeneratedFile(relativePath: string, code: string) {
  const filePath = path.join(OUT_DIR, relativePath);
  const formatted = await prettier.format(code, {
    parser: "typescript",
    printWidth: 80,
    semi: true,
    singleQuote: false,
    trailingComma: "all",
  });

  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, formatted);
  writtenFiles.push(relativePath);
}

async function main() {
  const pageLoads = await loadAll<PageSchema>(PAGES_DIR);
  const collectionLoads = await loadAll<CollectionSchema>(COLLECTIONS_DIR);

  const pageSlugs = new Set<string>();
  for (const loaded of pageLoads) {
    const slug = loaded.schema?.page?.slug;
    if (!slug) continue;
    if (pageSlugs.has(slug)) {
      error({
        owner: `page "${slug}"`,
        message: "Duplicate page slug.",
        suggestion: "Each page schema must have a unique page.slug.",
      });
    }
    pageSlugs.add(slug);
  }

  const collectionSlugs = new Set<string>();
  for (const loaded of collectionLoads) {
    const slug = loaded.schema?.postType?.slug;
    if (!slug) continue;
    if (collectionSlugs.has(slug)) {
      error({
        owner: `collection "${slug}"`,
        message: "Duplicate collection slug.",
        suggestion: "Each collection schema must have a unique postType.slug.",
      });
    }
    collectionSlugs.add(slug);
  }

  for (const loaded of collectionLoads) {
    validateCollection(loaded, collectionSlugs);
  }
  for (const loaded of pageLoads) {
    validatePage(loaded, collectionSlugs);
  }

  for (const loaded of collectionLoads) {
    const slug = loaded.schema?.postType?.slug;
    if (!slug || !Array.isArray(loaded.schema.fields)) continue;
    for (const field of loaded.schema.fields) {
      for (const target of dependenciesOf(field)) {
        if (target === slug) {
          error({
            owner: `collection "${slug}"`,
            field: field.name,
            message: "Self-referential collection relationships are not supported.",
            suggestion:
              "Resolve the relationship in the consuming component or remove it from the collection schema.",
          });
        }
      }
    }
  }

  if (errors.length > 0) {
    printProblems("Schema validation failed", errors);
    printProblems("Warnings", warnings);
    console.error(
      `\nNo files were written. Fix the ${errors.length} error(s) above and run the generator again.`
    );
    process.exit(1);
  }

  const collections = collectionLoads
    .map((loaded) => buildCollectionInfo(loaded))
    .filter((collection): collection is CollectionInfo => Boolean(collection))
    .sort((a, b) => a.slug.localeCompare(b.slug));
  const collectionsBySlug = new Map(
    collections.map((collection) => [collection.slug, collection])
  );

  const sharedSections = buildSharedSections(pageLoads);
  const pages = pageLoads
    .map((loaded) => buildPageInfo(loaded, sharedSections))
    .filter((page): page is PageInfo => Boolean(page))
    .sort((a, b) => a.slug.localeCompare(b.slug));

  if (errors.length > 0) {
    printProblems("Schema validation failed", errors);
    printProblems("Warnings", warnings);
    console.error(
      `\nNo files were written. Fix the ${errors.length} error(s) above and run the generator again.`
    );
    process.exit(1);
  }

  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  fs.mkdirSync(OUT_DIR, { recursive: true });

  await writeGeneratedFile("_shared.ts", renderSharedModule());

  for (const collection of collections) {
    await writeGeneratedFile(
      `collections/${fileSlug(collection.slug)}.ts`,
      renderCollectionModule(collection, collectionsBySlug)
    );
  }

  for (const section of sharedSections.values()) {
    await writeGeneratedFile(
      `sections/${fileSlug(section.name)}.ts`,
      renderSharedSectionModule(section, collectionsBySlug)
    );
  }

  for (const page of pages) {
    await writeGeneratedFile(
      `pages/${page.slug}.ts`,
      renderPageModule(page, sharedSections, collectionsBySlug)
    );
  }

  const indexExports = [
    ...collections.map(
      (collection) => `export * from "./collections/${fileSlug(collection.slug)}";`
    ),
    ...[...sharedSections.values()].map(
      (section) => `export * from "./sections/${fileSlug(section.name)}";`
    ),
    ...pages.map((page) => `export * from "./pages/${page.slug}";`),
  ];

  await writeGeneratedFile(
    "index.ts",
    `${HEADER}\n\n${indexExports.join("\n")}\n`
  );

  functionRows.push({
    name: "toRecord",
    owner: "_shared.ts",
    kind: "helper",
  });

  fs.writeFileSync(
    path.join(OUT_DIR, "_report.md"),
    renderReport(collections, pages)
  );

  printProblems("Warnings", warnings);

  console.log(
    `Generated ${writtenFiles.length} TypeScript files and ${functionRows.length} functions in ${OUT_DIR}.`
  );
  console.log(`Report: ${path.join(OUT_DIR, "_report.md")}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
