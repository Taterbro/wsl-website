import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

type Field = {
  name: string;
  type: string;
  fields?: Field[];
  collection?: string;
};
type Section = { label: string; fields: Field[] };
type Ctx = { used: Set<string> }; // collections a section depends on

const OUT = "lib/cms/generated";
const HEADER = `// AUTO-GENERATED by scripts/generate-next.ts. DO NOT EDIT.
/* eslint-disable @typescript-eslint/no-explicit-any, @typescript-eslint/no-unused-vars */
`;
const HELPERS = `import { toStr, toArray, toImage, toIds, pickByIds, type CmsImage } from "../normalize";`;

const pascal = (s: string) =>
  s
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");
const allVar = (slug: string) => `all_${slug.replace(/\W/g, "_")}`;

async function loadAll(dir: string) {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".ts"));

  return Promise.all(
    files.map(async (f) => {
      const filePath = path.resolve(dir, f);
      const fileUrl = pathToFileURL(filePath);

      return (await import(fileUrl.href)).default;
    })
  );
}

const collections = new Map<string, { type: string; fn: string }>();
function collection(slug?: string) {
  const c = slug ? collections.get(slug) : undefined;
  if (!c)
    throw new Error(`Relationship points at unknown collection "${slug}"`);
  return c;
}

const claimed = new Set<string>();
function claim(name: string) {
  if (claimed.has(name)) {
    throw new Error(
      `Name collision: "${name}" would be generated twice. Rename the section.`
    );
  }
  claimed.add(name);
}

// ---- schema field -> TypeScript type
function tsType(f: Field, ctx: Ctx): string {
  switch (f.type) {
    case "text":
    case "textarea":
    case "url":
      return "string";
    case "image":
      return "CmsImage | null";
    case "repeater":
      return `Array<{ ${f
        .fields!.map((s) => `${s.name}: ${tsType(s, ctx)};`)
        .join(" ")} }>`;
    case "relationship":
      ctx.used.add(f.collection!);
      return `${collection(f.collection).type}[]`;
    default:
      throw new Error(`Unknown field type "${f.type}" (field "${f.name}")`);
  }
}

// ---- schema field -> expression that turns the raw value into the clean one
function mapExpr(f: Field, src: string): string {
  switch (f.type) {
    case "text":
    case "textarea":
    case "url":
      return `toStr(${src})`;
    case "image":
      return `toImage(${src})`;
    case "repeater":
      return `toArray(${src}).map((row) => ({ ${f
        .fields!.map((s) => `${s.name}: ${mapExpr(s, `row.${s.name}`)}`)
        .join(", ")} }))`;
    case "relationship":
      return `pickByIds(${allVar(f.collection!)}, toIds(${src}))`;
    default:
      throw new Error(`Unknown field type "${f.type}" (field "${f.name}")`);
  }
}

function emitSection(pageSlug: string, name: string, section: Section) {
  const T = pascal(name);
  const fn = `get${T}`;
  claim(T);
  claim(fn);

  const ctx: Ctx = { used: new Set() };
  const typeBody = section.fields
    .map((f) => `  ${f.name}: ${tsType(f, ctx)};`)
    .join("\n");
  const mapBody = section.fields
    .map((f) => `    ${f.name}: ${mapExpr(f, `s.${f.name}`)},`)
    .join("\n");
  const loads = [...ctx.used]
    .map((c) => `  const ${allVar(c)} = await ${collection(c).fn}();`)
    .join("\n");

  const code = `export type ${T} = {
${typeBody}
};

export async function ${fn}(): Promise<${T}> {
  const acf = await getPageAcf("${pageSlug}");
  const s = (acf.${name} ?? {}) as Record<string, any>;
${loads}
  return {
${mapBody}
  };
}
`;
  return { code, used: ctx.used };
}

function emitCollection(schema: any) {
  const { slug, label } = schema.postType;
  const fields: Field[] = schema.fields;
  if (fields.some((f) => f.type === "relationship")) {
    throw new Error(
      `Collection "${slug}": relationships inside collections aren't supported yet.`
    );
  }
  const { type: T, fn } = collection(slug);
  claim(T);
  claim(fn);
  claim(`${fn.replace(/s$/, "")}`); // getProject (single)
  const single = fn.replace(/s$/, "");
  const ctx: Ctx = { used: new Set() };

  return `${HEADER}import "server-only";

import { cacheLife, cacheTag } from "next/cache";

import { cmsGet } from "../client";
${HELPERS}

export type ${T} = {
  id: number;
  slug: string;
  title: string;
${fields.map((f) => `  ${f.name}: ${tsType(f, ctx)};`).join("\n")}
};

type ${T}Body = {
  id: number;
  slug: string;
  title: { rendered: string };
  acf: Record<string, any> | null;
};

function to${T}(b: ${T}Body): ${T} {
  const a = b.acf ?? {};
  return {
    id: b.id,
    slug: b.slug,
    title: b.title.rendered,
${fields.map((f) => `    ${f.name}: ${mapExpr(f, `a.${f.name}`)},`).join("\n")}
  };
}

export async function ${fn}(): Promise<${T}[]> {
  "use cache";
  cacheLife("hours");
  cacheTag("collection_${slug}");

  const items = await cmsGet<${T}Body[]>("${slug}", {
    per_page: 100,
    _fields: "id,slug,title,acf",
  });
  return items.map(to${T});
}

export async function ${single}(slug: string): Promise<${T} | null> {
  const all = await ${fn}();
  return all.find((p) => p.slug === slug) ?? null;
}
`;
}

async function main() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  const write = (file: string, content: string) =>
    fs.writeFileSync(path.join(OUT, file), content);
  const index: string[] = [];

  // Collections first, so pages can reference them
  const collectionSchemas = await loadAll("cms/collections");
  for (const s of collectionSchemas) {
    const { slug, label } = s.postType;
    collections.set(slug, { type: pascal(slug), fn: `get${pascal(label)}` });
  }
  for (const s of collectionSchemas) {
    const slug = s.postType.slug;
    write(`collection-${slug}.ts`, emitCollection(s));
    index.push(`export * from "./collection-${slug}";`);
  }

  // Pages
  for (const s of await loadAll("cms/pages")) {
    const slug = s.page.slug;
    const used = new Set<string>();
    const blocks: string[] = [];

    for (const [name, section] of Object.entries<Section>(s.sections)) {
      const out = emitSection(slug, name, section);
      blocks.push(out.code);
      out.used.forEach((c) => used.add(c));
    }

    const imports = [...used]
      .map(
        (c) =>
          `import { ${collection(c).fn}, type ${
            collection(c).type
          } } from "./collection-${c}";`
      )
      .join("\n");

    write(
      `page-${slug}.ts`,
      `${HEADER}import "server-only";

import { getPageAcf } from "../page";
${HELPERS}
${imports}

${blocks.join("\n")}`
    );
    index.push(`export * from "./page-${slug}";`);
  }

  write("index.ts", `${HEADER}${index.join("\n")}\n`);
  console.log("Next.js fetchers generated.");
}

main();
